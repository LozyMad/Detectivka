function freezeRubric(questions) {
  if (questions.length !== rules.length) return null;
  const seen = new Set();
  const result = questions.map(question => {
    const index = rules.findIndex(rule => rule.aliases.some(text => normalize(text) === normalize(question.question_text)));
    if (index < 0 || seen.has(index) || String(question.criteria || '').trim()) return null;
    seen.add(index);
    const {answer, note} = rules[index];
    const items = rules[index].items.map(([id, points, text]) => ({id, points, text}));
    if (index === 5 && normalize(question.question_text).includes('в автомастерской')) {
      items[4] = {id: 'defense', points: 1, text: 'Томаш заступался за Марека и просил отсрочку. Эпизод с Rolex для узкой формулировки не требуется.'};
    }
    return {...question, ai_rule: {version: VERSION, answer, items, note}};
  });
  return result.some(item => !item) ? null : result;
}

function describeRule(rule) {
  return rule.answer+'\n\nКритерии:\n'+rule.items.map(item=>`${item.points} б.: ${item.text}`).join('\n')+'\n\n'+rule.note;
}

